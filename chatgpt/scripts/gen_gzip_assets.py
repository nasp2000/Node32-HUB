#!/usr/bin/env python3
"""Generate pre-gzipped copies of the big static web assets.

Why: the ESP32-S3 ROM exposes tdefl_compress_mem_to_mem (see esp32s3.rom.ld)
but it is a stub that returns 0, so the firmware cannot gzip at runtime without
bundling a compressor (the project does not add libraries for this). These
assets never change at runtime, so they are compressed here, committed, and
served with Content-Encoding: gzip.

Usage:
  python chatgpt/scripts/gen_gzip_assets.py           # regenerate the header
  python chatgpt/scripts/gen_gzip_assets.py --check   # fail if the header is stale
"""
import gzip
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]          # <repo>/chatgpt
OUT = ROOT / "src" / "webpages" / "assets" / "generated_gzip_assets.h"

# (C symbol, source file, raw-string delimiter, minimum length)
ASSETS = [
    ("GZ_LANG_UI_EN", "src/languages/lang_en_ui.h", "JSON", 4096),
    ("GZ_LANG_UI_PT", "src/languages/lang_pt_ui.h", "JSON", 4096),
    ("GZ_CORE_CSS",   "src/webpages/core_css.h",    "CSS",  1024),
    ("GZ_CHART_JS",   "src/webpages/assets/page_charts_vendor.h", "CHARTJS", 4096),
    ("GZ_ZOOM_JS",    "src/webpages/assets/page_charts_vendor.h", "ZOOMJS",  1024),
]


def extract(path: Path, delim: str) -> bytes:
    """Return the bytes inside R"DELIM( ... )DELIM" from `path`."""
    text = path.read_text(encoding="utf-8")
    m = re.search(r'R"' + re.escape(delim) + r'\((.*?)\)' + re.escape(delim) + r'"', text, re.S)
    if not m:
        raise SystemExit(f"[gzip-assets] {path}: R\"{delim}(...) not found")
    return m.group(1).encode("utf-8")


def build_header() -> str:
    out = [
        "// generated_gzip_assets.h — AUTO-GENERATED by scripts/gen_gzip_assets.py",
        "// Do not edit. Re-run the script after changing any of the sources below.",
        "//",
        "// Pre-compressed copies of the big static payloads (gzip, RFC 1952).",
        "// Served with Content-Encoding: gzip when the client accepts it.",
        "#pragma once",
        "#include <Arduino.h>",
        "",
    ]
    for sym, rel, delim, minlen in ASSETS:
        src = ROOT / rel
        data = extract(src, delim)
        if len(data) < minlen:
            raise SystemExit(f"[gzip-assets] {rel}: payload too small ({len(data)})")
        gz = gzip.compress(data, compresslevel=9, mtime=0)
        out.append(f"// {rel} ({delim}): {len(data)} B -> {len(gz)} B")
        out.append(f"const uint32_t {sym}_RAW_LEN = {len(data)};")
        out.append(f"const uint32_t {sym}_LEN = {len(gz)};")
        out.append(f"const uint8_t {sym}[] PROGMEM = {{")
        line = []
        for i, b in enumerate(gz):
            line.append(f"0x{b:02x}")
            if len(line) == 24:
                out.append("  " + ",".join(line) + ",")
                line = []
        if line:
            out.append("  " + ",".join(line) + ",")
        out.append("};")
        out.append("")
    return "\n".join(out) + "\n"


def check_header() -> int:
    """Verify the committed header still decodes to the current sources.

    Compares the DECOMPRESSED payload, never the compressed bytes: gzip output
    is not portable across zlib implementations (Ubuntu 24.04 links zlib-ng),
    so a byte-for-byte comparison made the check fail on CI while passing on the
    machine that generated the file. A stale header (source edited without
    regenerating) still fails because the payload differs.
    """
    if not OUT.exists():
        print(f"[gzip-assets] MISSING {OUT}")
        return 1
    text = OUT.read_text(encoding="utf-8")
    problems = []
    for sym, rel, delim, _minlen in ASSETS:
        payload = extract(ROOT / rel, delim)
        m = re.search(re.escape(sym) + r"\[\] PROGMEM = \{(.*?)\};", text, re.S)
        if not m:
            problems.append(f"{sym}: array missing from the header")
            continue
        data = bytes(int(b, 16) for b in re.findall(r"0x([0-9a-f]{2})", m.group(1)))
        try:
            back = gzip.decompress(data)
        except Exception as exc:          # corrupt/truncated gzip
            problems.append(f"{sym}: cannot decode ({exc})")
            continue
        if back != payload:
            problems.append(f"{sym}: header {len(back)} B != source {len(payload)} B "
                            f"({rel})")
    if problems:
        for p in problems:
            print(f"[gzip-assets] STALE {p}")
        print("[gzip-assets] STALE: run python chatgpt/scripts/gen_gzip_assets.py")
        return 1
    print("[gzip-assets] OK")
    return 0


def main() -> int:
    if "--check" in sys.argv:
        return check_header()
    header = build_header()
    OUT.write_text(header, encoding="utf-8")
    total_raw = sum(len(extract(ROOT / rel, d)) for _, rel, d, _ in ASSETS)
    print(f"[gzip-assets] wrote {OUT} ({total_raw} B raw)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
