"""
ota_keygen.py — Generate RSA 2048-bit keypair for OTA firmware signing.

Usage:
    python scripts/ota_keygen.py

Output:
    ota_private.pem            → KEEP SECRET, never commit to git
    src/ota_pubkey.h           → embedded public key (commit to git)
"""

import os, sys
from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.asymmetric import rsa
from cryptography.hazmat.primitives.serialization import (
    Encoding, PrivateFormat, PublicFormat, NoEncryption, BestAvailableEncryption
)

PROJECT_DIR = os.path.normpath(os.path.join(os.path.dirname(__file__), ".."))

def main():
    key = rsa.generate_private_key(public_exponent=65537, key_size=2048)

    priv_path = os.path.join(PROJECT_DIR, "ota_private.pem")
    with open(priv_path, "wb") as f:
        f.write(key.private_bytes(
            Encoding.PEM, PrivateFormat.PKCS8, NoEncryption()
        ))
    os.chmod(priv_path, 0o600)
    print(f"[OTA_KEYGEN] Private key: {priv_path} (KEEP SECRET!)")

    pub_der = key.public_key().public_bytes(Encoding.DER, PublicFormat.PKCS1)
    hex_bytes = ", ".join(f"0x{b:02x}" for b in pub_der)

    pub_h_path = os.path.join(PROJECT_DIR, "src", "ota_pubkey.h")
    with open(pub_h_path, "w") as f:
        f.write("#pragma once\n")
        f.write("#include <pgmspace.h>\n")
        f.write(f"// RSA 2048-bit public key (PKCS#1 DER, {len(pub_der)} bytes)\n")
        f.write(f"static const uint8_t OTA_PUBKEY_DER[] PROGMEM = {{\n    {hex_bytes}\n}};\n")
        f.write(f"static const size_t OTA_PUBKEY_DER_LEN = {len(pub_der)};\n")
    print(f"[OTA_KEYGEN] Public key header: {pub_h_path}")

    gitignore_path = os.path.join(PROJECT_DIR, ".gitignore")
    if os.path.exists(gitignore_path):
        with open(gitignore_path, "r") as f:
            content = f.read()
        if "ota_private.pem" not in content:
            with open(gitignore_path, "a") as f:
                f.write("\n# OTA signing private key (generated by ota_keygen.py)\nota_private.pem\n")
            print("[OTA_KEYGEN] Added ota_private.pem to .gitignore")

    print("[OTA_KEYGEN] Done. Run sign_firmware.py after each build to sign firmware.")

if __name__ == "__main__":
    main()
