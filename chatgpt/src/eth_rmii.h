// =============================================================
// eth_rmii.h — RMII Ethernet configuration for ESP32-P4
// =============================================================
// Purpose: define RMII pins and expose the same minimal API as eth_w5500.h.
// The driver is selected at compile time by TARGET_BOARD_P4.
// When TARGET_BOARD_P4 is not defined this file provides empty stubs so
// any file that includes both eth_w5500.h and eth_rmii.h compiles cleanly.
//
// Hardware: ESP32-P4 internal RMII MAC + external IP101GRI PHY.
// Reference clock: 50 MHz input on GPIO50 (IP101GRI crystal 25 MHz x2 PLL).
//
// Only used when TARGET_BOARD_P4==1 AND ENABLE_ETHERNET==1.
// See Docs/esp32_p4_port_plan.md for the full migration plan.

#pragma once
#include "feature_flags.h"

#if ENABLE_ETHERNET==1 && defined(TARGET_BOARD_P4) && TARGET_BOARD_P4==1
#include <Arduino.h>

// ---------------------------------------------------------------------------
// RMII pin defaults — overridable from board_pins.h (applied before this file).
// All values match the Waveshare ESP32-P4-Module-DEV-KIT schematic.
// ---------------------------------------------------------------------------
#ifndef ETH_RMII_TXD0_PIN
#define ETH_RMII_TXD0_PIN        34
#endif
#ifndef ETH_RMII_TXD1_PIN
#define ETH_RMII_TXD1_PIN        35
#endif
#ifndef ETH_RMII_RXD0_PIN
#define ETH_RMII_RXD0_PIN        30
#endif
#ifndef ETH_RMII_RXD1_PIN
#define ETH_RMII_RXD1_PIN        29
#endif
#ifndef ETH_RMII_TX_EN_PIN
#define ETH_RMII_TX_EN_PIN       49
#endif
#ifndef ETH_RMII_CRS_DV_PIN
#define ETH_RMII_CRS_DV_PIN      28
#endif
// GPIO50: external 50 MHz reference clock input (generated by IP101GRI 25 MHz crystal x2 PLL).
#ifndef ETH_RMII_REF_CLK_PIN
#define ETH_RMII_REF_CLK_PIN     50
#endif
#ifndef ETH_RMII_MDC_PIN
#define ETH_RMII_MDC_PIN         31
#endif
#ifndef ETH_RMII_MDIO_PIN
#define ETH_RMII_MDIO_PIN        52
#endif
#ifndef ETH_RMII_PHY_RESET_PIN
#define ETH_RMII_PHY_RESET_PIN   51
#endif
// IP101GRI default MDIO PHY address.
#ifndef ETH_RMII_PHY_ADDR
#define ETH_RMII_PHY_ADDR         1
#endif

// ---------------------------------------------------------------------------
// Minimal API — same signatures as eth_w5500.h so callers are source-compatible.
// ---------------------------------------------------------------------------
void      ethernetBegin();
int       ethernetStatus();
void      ethernetLoop();
IPAddress ethernetLocalIP();
void      ethernetFlushBootLogToSD();
void      ethernetBootLogLine(const char* msg);

// Set true while a reinit task is running; checked by ethernetLoop() to skip reads.
extern volatile bool _ethReinitTaskRunning;

#else
// Stubs when disabled or not on P4 — inline to avoid linker symbols.
static inline void      ethernetBegin()               {}
static inline int       ethernetStatus()              { return -1; }
static inline void      ethernetLoop()                {}
static inline IPAddress ethernetLocalIP()             { return IPAddress(0,0,0,0); }
static inline void      ethernetFlushBootLogToSD()    {}
static inline void      ethernetBootLogLine(const char*) {}
#endif // ENABLE_ETHERNET && TARGET_BOARD_P4
