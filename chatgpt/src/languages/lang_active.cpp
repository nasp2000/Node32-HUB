// Default: English. Changed by setupLanguage() after config is loaded.
const LangStrings* activeLang = &LANG_EN;

// Default: English UI JSON. Changed by setupLanguage() after config is loaded.
const char* activeLangUiJson = LANG_UI_EN;

// Default: English UI language code. Changed by setupLanguage().
const char* activeLangCode = "en";

void setupLanguage() {
    String lang = configManager.getSystemLanguage();
    if (lang == "en") {
        activeLang      = &LANG_EN;
        activeLangUiJson = LANG_UI_EN;
        activeLangCode   = "en";
    } else {
        activeLang      = &LANG_PT;
        activeLangUiJson = LANG_UI_PT;
        activeLangCode   = "pt";
    }
}
